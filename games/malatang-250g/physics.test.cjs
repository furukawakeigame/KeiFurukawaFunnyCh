const context = vm.createContext({ window: { addEventListener() {} }, document: { addEventListener() {}, getElementById(id) { if (!nodes.has(id)) nodes.set(id, element()); return nodes.get(id); }, createElement: element }, localStorage: { getItem() { return null; }, setItem() {} }, Image: class {}, requestAnimationFrame() {}, Math, console, navigator: {} });
const source = fs.readFileSync(__dirname + '/index.html', 'utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
vm.runInContext(source, context);
const run = code => vm.runInContext(code, context);
run('begin(); selected=3; drop();');
assert.equal(run('bodies.length'), 1);
run('drop()');
assert.equal(run('bodies.length'), 1, 'rapid duplicate drops should be ignored');
run('for(let i=0;i<1200;i++)step(1/120)');
assert.ok(run('bodies[0].y > 440 && bodies[0].y < 480'), 'meatball should rest on bowl floor');
assert.ok(run('Math.abs(bodies[0].vy)<5'), 'resting body should settle');
run('begin(); for(let n=0;n<32;n++){selected=n%8;dropX=92+(n*73)%356;drop();for(let i=0;i<90;i++)step(1/120)} for(let i=0;i<600;i++)step(1/120)');
assert.equal(run('bodies.length'), 32);
assert.ok(run('bodies.every(b=>Number.isFinite(b.x+b.y+b.a)&&b.x>0&&b.x<540&&b.y<545)'), 'mixed food pile must stay finite and on the table');
run('clock+=1;drop()');
assert.equal(run('bodies.length'), 32, 'capacity must be enforced');
run('begin();selected=3;drop();bodies[0].g=250;bodies[0].y=450;$("weigh").onclick()');
assert.equal(run('mode'), 'result');
assert.equal(run('best'), 0);
assert.ok(nodes.get('result-title').textContent.includes('ぴったり'));
run('clock+=1;drop()');
assert.equal(run('bodies.length'), 1, 'result screen must block drops');
run('begin()');
assert.equal(run('bodies.length'), 0);
assert.equal(run('mode'), 'play');
run("const event=(x,y,id=1)=>({clientX:x,clientY:y,pointerId:id,button:0,preventDefault(){}});const card=$('ingredients').children[3];startDrag(event(620,100),3,card);moveDrag(event(270,150));finishDrag(event(270,150));");
