assert.equal(run('bodies[0].y'),150,'drop should start at the release position');
assert.equal(run('drag'),null);
run('clock+=1;startDrag(event(620,100),3,card);moveDrag(event(610,300));finishDrag(event(610,300));');
assert.equal(run('bodies.length'),1,'outside drop must cancel');

run('startDrag(event(270,100),3,card);finishDrag(event(270,100));');
assert.equal(run('bodies.length'),1,'a tap must not drop a food');
run('startDrag(event(620,100,2),3,card);moveDrag(event(270,150,2));cancelDrag();');
assert.equal(run('bodies.length'),1,'cancelled touch must not add food');
assert.equal(run('ghost.hidden'),true);
run('startDrag(event(620,100,3),3,card);moveDrag(event(270,150,3));finishDrag(event(270,150,3));');
assert.equal(run('bodies.length'),2);
assert.ok(run('bodies[1].y<bodies[0].y'),'dropping onto another item should avoid embedded spawn');
run('begin();startDrag(event(620,100),3,card);moveDrag(event(38,400));finishDrag(event(38,400));for(let n=0;n<1200;n++)step(1/120);');
assert.equal(run('bodies.length'),1,'outside bowl placement must be retained');
assert.ok(run('bodies[0].y>500&&bodies[0].y<545'),'outside item must rest on table');
assert.equal(run('bowlWeight()'),0,'outside items must not be weighed');
run('clock+=1;dropX=270;drop();for(let n=0;n<1200;n++)step(1/120)');
assert.equal(run('bowlWeight()'),run('bodies[1].g'),'only inside bowl weight counts');
assert.ok(run('foods[0].w>foods[2].w&&foods[7].w>foods[2].w&&foods[3].w<foods[5].w&&foods[1].w<foods[5].w'));
run('begin();clock=9;updateChef()');
assert.equal(run('chefPhase'),'question');
assert.ok(!nodes.get('chef-speech').textContent.includes('答え'));
run('clock=16;updateChef()');
assert.equal(run('quizIndex'),1);
run('begin();selected=3;dropX=35;drop(400);for(let n=0;n<240;n++){step(1/120);updateChef()}');
assert.equal(run('chefPhase'),'angry');
assert.equal(run('scoldCount'),1);
run("chefImage={name:'normal'};chefAngryImage={name:'angry'}");
assert.equal(run('currentChefImage().name'),'angry');
run('for(let n=0;n<600;n++){step(1/120);updateChef()}');
assert.equal(run('scoldCount'),1,'one spill must not trigger repeated scolding');
assert.notEqual(run('chefPhase'),'angry','quiz must resume after scolding');
assert.equal(run('currentChefImage().name'),'normal');
run('begin();selected=3;dropX=270;drop();for(let n=0;n<600;n++){step(1/120);updateChef()}');
assert.equal(run('scoldCount'),0,'normal bowl drops must not trigger anger');
console.log('PASS: physics, scoring, drag/drop, outside placement, chef quiz/answer, spill reaction, quiz resume');
